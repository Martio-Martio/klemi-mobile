const int longueurTelephoneParDefaut = 15;

int longueurMaxIndicatif(String indicatif) =>
    longueursTelephone[indicatif] ?? longueurTelephoneParDefaut;

/// Ne garde que les chiffres, puis coupe au plafond de l'indicatif.
String recouperNumero(String saisie, int maximum) {
  final chiffres = saisie.replaceAll(RegExp(r'\D'), '');
  if (maximum <= 0 || chiffres.isEmpty) return '';
  if (chiffres.length <= maximum) return chiffres;
  return chiffres.substring(0, maximum);
}

/// Numéro envoyé à l'API : indicatif collé aux chiffres locaux.
String composerNumero(String indicatif, String chiffres) =>
    '$indicatif${recouperNumero(chiffres, longueurMaxIndicatif(indicatif))}';
